"""Dimension of the dynamical Lie algebra generated by a set of Pauli strings.

The dynamical Lie algebra (DLA) of an ansatz is the real span closed under
commutation of its gate generators. Its dimension counts every direction the
circuit can reach at any depth, so it is the reachable set of the family. It is
also the sharpest structural predictor of a barren plateau: the gradient
variance falls like ``1 / dim(g)`` (Ragone et al. 2024), so a DLA that grows to
the full ``4**n - 1`` of ``su(2**n)`` marks the exponentially untrainable regime,
while a DLA that grows as a polynomial in ``n`` does not.

Method
------
Every generator is a dense Hermitian matrix built from a Pauli string. The
closure is grown by a breadth-first search over commutators. A new element is
kept only if it is linearly independent of the basis so far, which is tested by
Gram-Schmidt in the Hilbert-Schmidt inner product ``<A, B> = Tr[A' B]``. The
count of independent elements is the dimension.

``i [A, B]`` is used, not ``[A, B]``, because the commutator of two Hermitian
matrices is anti-Hermitian and the factor ``i`` returns it to the Hermitian real
vector space the basis lives in.

Cost
----
The closure stores up to ``4**n - 1`` dense vectors of length ``4**n``. This is
exponential in ``n`` by nature, not by implementation: the object being measured
is exponentially large whenever the DLA is full. The width is therefore capped
by memory at roughly ``n = 6``. The caller passes ``dim_cap`` to stop early and
to record that the true dimension is at least the cap.
"""

from __future__ import annotations

import functools
from collections.abc import Sequence

import numpy as np
from numpy.typing import NDArray

_PAULI: dict[str, NDArray[np.complexfloating]] = {
    "I": np.eye(2, dtype=complex),
    "X": np.array([[0, 1], [1, 0]], dtype=complex),
    "Y": np.array([[0, -1j], [1j, 0]], dtype=complex),
    "Z": np.array([[1, 0], [0, -1]], dtype=complex),
}


def pauli_matrix(word: str) -> NDArray[np.complexfloating]:
    """Return the dense matrix of a Pauli string such as ``"IXZ"``.

    Args:
        word: A string of the letters I, X, Y, Z. Its length is the qubit count.

    Returns:
        A ``2**len(word)`` by ``2**len(word)`` Hermitian, unitary matrix.

    Raises:
        KeyError: If the string holds a letter other than I, X, Y or Z.

    Examples:
        >>> import numpy as np
        >>> np.allclose(pauli_matrix("X"), [[0, 1], [1, 0]])
        True
    """
    return functools.reduce(np.kron, [_PAULI[letter] for letter in word])


def lie_closure_dimension(
    generators: Sequence[str], dim_cap: int | None = None, tol: float = 1e-9
) -> tuple[int, bool]:
    """Return the dimension of the Lie closure of a set of Pauli strings.

    Args:
        generators: The Pauli strings that generate the algebra. They must all
            have the same length, which is the qubit count.
        dim_cap: Optional early stop. When the basis reaches this size the search
            returns, and the returned flag says the true dimension is at least
            this value. ``None`` means run to closure, capped only by
            ``4**n - 1``.
        tol: Norm below which a Gram-Schmidt residual counts as zero, so the new
            element is treated as already in the span.

    Returns:
        A pair ``(dimension, capped)``. ``capped`` is True when the search was
        stopped by ``dim_cap`` before the algebra closed, so ``dimension`` is a
        lower bound rather than the exact value.

    Examples:
        >>> # X and Z on one qubit close to su(2), which has dimension 3.
        >>> lie_closure_dimension(["X", "Z"])
        (3, False)
    """
    if not generators:
        return 0, False
    n = len(generators[0])
    ceiling = 4 ** n - 1
    cap = ceiling if dim_cap is None else min(dim_cap, ceiling)

    basis: list[NDArray[np.complexfloating]] = []

    def absorb(matrix: NDArray[np.complexfloating]) -> bool:
        """Add the flattened matrix to the basis if it is independent."""
        vector = matrix.reshape(-1).astype(complex)
        for element in basis:
            vector = vector - np.vdot(element, vector) * element
        norm = np.linalg.norm(vector)
        if norm > tol:
            basis.append(vector / norm)
            return True
        return False

    frontier = [pauli_matrix(word) for word in generators]
    reshaped_generators = [g.reshape(-1) for g in frontier]
    frontier = [g for g in frontier if absorb(g)]

    while frontier and len(basis) < cap:
        current, frontier = frontier, []
        for left in current:
            # Commute new elements with each other and with the generators. The
            # second set is what lets a single deep element reach the whole
            # algebra, so it must not be dropped.
            for right_flat in reshaped_generators:
                right = right_flat.reshape(left.shape)
                bracket = 1j * (left @ right - right @ left)
                if absorb(bracket):
                    frontier.append(bracket)
                    if len(basis) >= cap:
                        break
            if len(basis) >= cap:
                break

    return len(basis), len(basis) >= cap and len(basis) < ceiling
